// ── Spine Node Shape (mirrors Canvas3D spineNodes) ──

export interface SpineNode {
  z: number;
  y: number;
  xArch: number;
  radius: number;
  baseRadius: number;
}

// ── Hull SDF Approximation ──

/**
 * Build an analytic swept-sphere SDF approximation of the carapace hull from
 * the spine nodes. The hull is a surface of revolution whose cross-section at
 * each z is a circle of radius `node.radius` centered at (node.xArch, node.y, z).
 *
 * This SDF is an approximation intended for blending computations only — the
 * visible hull mesh remains the high-resolution parametric surface built by
 * Canvas3D. The approximation is accurate to within a few percent of the hull
 * radius, which is sufficient for smooth-union fillets.
 *
 * @param spineNodes The hull spine nodes (from Canvas3D buildSpaceship).
 * @param crossSectionHeightFactor Vertical scale of the hull cross-section
 *   ellipse (1 = circular). Canvas3D's leviathan profile flattens sections
 *   to ~0.84; passing it here keeps blend bridges aligned with the surface.
 * @returns A signed distance function approximating the hull surface.
 */
export function buildHullSDF(
  spineNodes: SpineNode[],
  crossSectionHeightFactor: number = 1,
): SDF {
  if (spineNodes.length === 0) {
    return () => Infinity;
  }

  const sorted = [...spineNodes].sort((a, b) => a.z - b.z);

  const sampleSpine = (
    z: number,
  ): { cx: number; cy: number; cz: number; r: number } => {
    if (z <= sorted[0].z) {
      const n = sorted[0];
      return { cx: n.xArch, cy: n.y, cz: n.z, r: n.radius };
    }
    const last = sorted[sorted.length - 1];
    if (z >= last.z) {
      return { cx: last.xArch, cy: last.y, cz: last.z, r: last.radius };
    }
    let lo = 0;
    let hi = sorted.length - 1;
    while (hi - lo > 1) {
      const mid = (lo + hi) >> 1;
      if (sorted[mid].z < z) lo = mid;
      else hi = mid;
    }
    const a = sorted[lo];
    const b = sorted[hi];
    const t = (z - a.z) / (b.z - a.z);
    return {
      cx: a.xArch + (b.xArch - a.xArch) * t,
      cy: a.y + (b.y - a.y) * t,
      cz: a.z + (b.z - a.z) * t,
      r: a.radius + (b.radius - a.radius) * t,
    };
  };

  // Elliptical cross-section approximation: scale the vertical axis of the
  // query point around the spine center by 1/heightFactor, turning the
  // ellipse into a circle in the scaled space.
  const hf = Math.max(0.1, crossSectionHeightFactor);

  return (p: THREE.Vector3): number => {
    let bestDist = Infinity;
    let bestR = 0;
    const zStep = sorted.length > 1
      ? (sorted[sorted.length - 1].z - sorted[0].z) / (sorted.length - 1)
      : 1;
    const window = Math.max(2, Math.ceil(zStep * 2));
    for (let dz = -window; dz <= window; dz++) {
      const z = p.z + dz * zStep * 0.25;
      const s = sampleSpine(z);
      const dx = p.x - s.cx;
      const dy = (p.y - s.cy) / hf;
      const dzz = p.z - s.cz;
      const dist = Math.sqrt(dx * dx + dy * dy + dzz * dzz);
      if (dist < bestDist) {
        bestDist = dist;
        bestR = s.r;
      }
    }
    return bestDist - bestR;
  };
}

// ── Blend Entity Types ──

/** Identifies what an SDF represents in a blend operation. */
export type BlendEntity =
  | { kind: 'hull' }
  | { kind: 'organ'; organType: string }
  | { kind: 'pipelineNode'; nodeId: string }
  | { kind: 'conduit'; conduitId: string };

/** The result of evaluating whether two entities should blend. */
export interface BlendDecision {
  shouldBlend: boolean;
  blendRadius: number;
  materialRole: 'carapace' | 'flesh' | 'vein';
  reason: string;
}

// ── Blend Rules Registry ──

type BlendRule = (a: BlendEntity, b: BlendEntity) => BlendDecision | null;

const noBlend = (
  reason: string,
  materialRole: 'carapace' | 'flesh' | 'vein' = 'flesh',
): BlendDecision => ({ shouldBlend: false, blendRadius: 0, materialRole, reason });

const blend = (
  blendRadius: number,
  materialRole: 'carapace' | 'flesh' | 'vein',
  reason: string,
): BlendDecision => ({ shouldBlend: true, blendRadius, materialRole, reason });

const isOrganType = (e: BlendEntity, ...types: string[]): e is { kind: 'organ'; organType: string } =>
  e.kind === 'organ' && types.includes(e.organType);

const isNode = (e: BlendEntity, ...ids: string[]): e is { kind: 'pipelineNode'; nodeId: string } =>
  e.kind === 'pipelineNode' && ids.includes(e.nodeId);

const isConduit = (e: BlendEntity): e is { kind: 'conduit'; conduitId: string } =>
  e.kind === 'conduit';

