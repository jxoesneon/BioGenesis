/**
 * Build a simple SDF approximation for a surface-mounted candidate organ.
 * Used for blend-bridge generation at the hull connection point.
 */
export function buildCandidateOrganSDF(
  organType: string,
  basePos: THREE.Vector3,
  normal: THREE.Vector3,
  size: number,
  stalkLength: number = 0,
): SDF | null {
  const offset = stalkLength > 0.01 ? stalkLength + size : size * 0.6;
  const center = basePos.clone().addScaledVector(normal, offset);

  if (organType === 'eye') {
    if (stalkLength > 0.01) {
      const stalkSDF = buildAlignedCapsuleSDF(basePos, center, 0.1);
      const eyeSDF = opTranslate(sdSphere(size), center);
      return opSmoothUnion(stalkSDF, eyeSDF, 0.08);
    }
    return opTranslate(sdSphere(size), center);
  }

  if (organType === 'neural') {
    const neuralCenter = basePos.clone().addScaledVector(normal, -size * 0.3);
    return opTranslate(sdSphere(size), neuralCenter);
  }

  if (organType === 'spore') {
    const sacCenter = basePos.clone().addScaledVector(normal, size * 0.7);
    return opTranslate(sdSphere(size), sacCenter);
  }

  if (organType === 'pectoralFin' || organType === 'caudalFluke' || organType === 'dorsalSail') {
    // Generate an ellipsoid/sphere at the root to blend the flat geometry into the hull
    const rootCenter = basePos.clone().addScaledVector(normal, size * 0.1);
    return opTranslate(sdSphere(size * 1.5), rootCenter);
  }

  if (organType === 'tentacle') {
    // Generate a capsule at the root to blend the spline into the hull
    const rootCenter = basePos.clone().addScaledVector(normal, size * 0.1);
    return opTranslate(sdSphere(size * 0.8), rootCenter);
  }
  
  if (organType === 'spiracle') {
    // Generate a torus SDF to blend the vent into the hull
    const torusCenter = basePos.clone().addScaledVector(normal, 0.0);
    return opTranslate(sdTorus(0.32, 0.15), torusCenter);
  }
  
  if (organType === 'rib') {
    // Generate a small capsule at the root to blend the rib into the hull
    const rootCenter = basePos.clone().addScaledVector(normal, size * 0.1);
    return opTranslate(sdSphere(size * 1.0), rootCenter);
  }
  
  if (organType === 'habitat') {
    // Generate a box SDF to blend the habitat block into the hull
    // A habitat is approx 1.8 x 1.4 x 1.8 (radius 0.9 x 0.7 x 0.9)
    const boxCenter = basePos.clone().addScaledVector(normal, 0.5);
    return opTranslate(sdBox(new THREE.Vector3(0.9, 0.7, 0.9)), boxCenter);
  }

  return null;
}

/**
 * Build a simple SDF approximation for a pipeline node.
 *
 * Each node type gets a primitive (sphere, capsule, cone, box, ellipsoid) that
 * approximates its shape near the connection point. The approximation is
 * sufficient for smooth-union fillet generation.
 *
 * @param nodeId Pipeline node ID (from NODE_IDS).
 * @param position World-space position of the node.
 * @param radius Approximate radius/size of the node.
 * @returns World-space SDF for the node.
 */
export function buildPipelineNodeSDF(
  nodeId: string,
  position: THREE.Vector3,
  radius: number,
): SDF {
  const pos = new THREE.Vector3(position.x, position.y, position.z);
  const r = Math.max(0.1, radius);

  // Spherical organs (most internal organs approximate as spheres)
  const sphericalNodes = [
    'plasma_gland', 'plasma_bladder', 'disruptor_gland',
    'heart_core', 'hemolymph_atrium',
    'brain_core',
    'ice_gizzard', 'bio_moss', 'habitat_chamber',
    'bio_nanite_bed', 'shield_emitter',
    'chitin_vertebra',
    'spiracle_vent', 'ocular_pod', 'cyber_airlock',
  ];
  if (sphericalNodes.includes(nodeId)) {
    return opTranslate(sdSphere(r), pos);
  }

  // Capsule organs (tubes/conduits along a direction)
  // For these, we use a sphere approximation since we don't know the direction
  // at this call site. The bridge generation uses a local region around the
  // connection point, so a sphere is sufficient.
  const capsuleNodes = [
    'plasma_trunk', 'caudal_manifold',
    'aorta_highway', 'flank_artery',
    'neuro_link', 'axon_cord', 'muscle_tendon',
  ];
  if (capsuleNodes.includes(nodeId)) {
    return opTranslate(sdSphere(r), pos);
  }

  // Carapace plate: flattened ellipsoid (wide, thin)
  if (nodeId === 'carapace_plate') {
    return opTranslate(sdEllipsoid(new THREE.Vector3(r * 1.5, r * 0.3, r * 1.5)), pos);
  }

  // Siphon vent nozzle: cone (exhaust shape)
  if (nodeId === 'siphon_vent_nozzle') {
    return opTranslate(sdCone(r * 0.8, r * 1.5), pos);
  }

  // Default: sphere approximation
  return opTranslate(sdSphere(r), pos);
}

/**
 * Build a capsule SDF for a conduit between two world-space points.
 *
 * @param start Conduit start point (world space).
 * @param end Conduit end point (world space).
 * @param radius Conduit radius.
 * @returns World-space capsule SDF.
 */
export function buildConduitSDF(
  start: THREE.Vector3,
  end: THREE.Vector3,
  radius: number,
): SDF {
  return buildAlignedCapsuleSDF(start, end, radius);
}

// ── Blend Bridge Manager ──

/**
 * Manages blend bridge meshes for a ship scene.
 *
 * Tracks all bridges by ID, allows removal and regeneration of individual
 * bridges (for drag operations on movable organs), and provides a clean
 * interface for Canvas3D to generate all approved bridges.
 */
export class BlendBridgeManager {
  private hullSDF: SDF | null = null;
  private spineNodes: SpineNode[] = [];
  private heightFactor: number = 1;
  private bridges: Map<string, THREE.Mesh> = new Map();
  private shipGroup: THREE.Group;

  constructor(shipGroup: THREE.Group) {
    this.shipGroup = shipGroup;
  }

  /** Update the hull SDF from current spine nodes (call after hull adaptation). */
  setHullSDF(spineNodes: SpineNode[], crossSectionHeightFactor: number = 1): void {
    this.spineNodes = spineNodes;
    this.heightFactor = crossSectionHeightFactor;
    this.hullSDF = buildHullSDF(spineNodes, crossSectionHeightFactor);
  }

  /** Get the current hull SDF (may be null if not set). */
  getHullSDF(): SDF | null {
    return this.hullSDF;
  }

  /**
   * Generate a bridge between a candidate organ and the hull.
   * Removes any existing bridge with the same ID first.
   *
   * @returns The bridge mesh, or null if no blend is approved.
   */
  generateOrganHullBridge(
    bridgeId: string,
    organType: string,
    basePos: THREE.Vector3,
    normal: THREE.Vector3,
    size: number,
    stalkLength: number,
    material: THREE.Material,
  ): THREE.Mesh | null {
    this.removeBridge(bridgeId);
    if (!this.hullSDF) return null;

    const organSDF = buildCandidateOrganSDF(organType, basePos, normal, size, stalkLength);
    if (!organSDF) return null;

    const decision = evaluateBlend({ kind: 'organ', organType }, { kind: 'hull' });
    if (!decision.shouldBlend) return null;

    const bridgeGeo = generateBlendBridge(organSDF, this.hullSDF, basePos, {
      blendRadius: decision.blendRadius,
      resolution: 24,
      regionPadding: Math.max(decision.blendRadius * 3, size * 1.5),
    });
    if (!bridgeGeo) return null;

    const bridgeMesh = new THREE.Mesh(bridgeGeo, material);
    bridgeMesh.userData = {
      name: `${organType} Hull Blend Bridge`,
      category: 'Anatomical Blend Fillet',
      desc: `Seamless SDF smooth-union fillet (${decision.reason}).`,
      isBlendBridge: true,
      bridgeId,
    };
    this.shipGroup.add(bridgeMesh);
    this.bridges.set(bridgeId, bridgeMesh);
    return bridgeMesh;
  }

  /**
   * Generate a bridge between a pipeline node and the hull.
   */
  generateNodeHullBridge(
    bridgeId: string,
    nodeId: string,
    nodePos: THREE.Vector3,
    nodeRadius: number,
    material: THREE.Material,
  ): THREE.Mesh | null {
    this.removeBridge(bridgeId);
    if (!this.hullSDF) return null;

    const decision = evaluateBlend(
      { kind: 'pipelineNode', nodeId },
      { kind: 'hull' },
    );
    if (!decision.shouldBlend) return null;

    const nodeSDF = buildPipelineNodeSDF(nodeId, nodePos, nodeRadius);
    const bridgeGeo = generateBlendBridge(nodeSDF, this.hullSDF, nodePos, {
      blendRadius: decision.blendRadius,
      resolution: 24,
      regionPadding: Math.max(decision.blendRadius * 3, nodeRadius * 1.5),
    });
    if (!bridgeGeo) return null;

    const bridgeMesh = new THREE.Mesh(bridgeGeo, material);
    bridgeMesh.userData = {
      name: `${nodeId} Hull Blend Bridge`,
      category: 'Anatomical Blend Fillet',
      desc: `Seamless SDF smooth-union fillet (${decision.reason}).`,
      isBlendBridge: true,
      bridgeId,
    };
    this.shipGroup.add(bridgeMesh);
    this.bridges.set(bridgeId, bridgeMesh);
    return bridgeMesh;
  }

  /**
   * Generate a bridge between two pipeline nodes (organ-to-organ).
   */
  generateNodeNodeBridge(
    bridgeId: string,
    nodeIdA: string,
    posA: THREE.Vector3,
    radiusA: number,
    nodeIdB: string,
    posB: THREE.Vector3,
    radiusB: number,
    material: THREE.Material,
  ): THREE.Mesh | null {
    this.removeBridge(bridgeId);

    const decision = evaluateBlend(
      { kind: 'pipelineNode', nodeId: nodeIdA },
      { kind: 'pipelineNode', nodeId: nodeIdB },
    );
    if (!decision.shouldBlend) return null;

    const sdfA = buildPipelineNodeSDF(nodeIdA, posA, radiusA);
    const sdfB = buildPipelineNodeSDF(nodeIdB, posB, radiusB);
    const connectionPoint = posA.clone().lerp(posB, 0.5);

    const bridgeGeo = generateBlendBridge(sdfA, sdfB, connectionPoint, {
      blendRadius: decision.blendRadius,
      resolution: 24,
      regionPadding: Math.max(decision.blendRadius * 3, Math.max(radiusA, radiusB) * 1.5),
    });
    if (!bridgeGeo) return null;

    const bridgeMesh = new THREE.Mesh(bridgeGeo, material);
    bridgeMesh.userData = {
      name: `${nodeIdA}-${nodeIdB} Blend Bridge`,
      category: 'Anatomical Blend Fillet',
      desc: `Seamless SDF smooth-union fillet (${decision.reason}).`,
      isBlendBridge: true,
      bridgeId,
    };
    this.shipGroup.add(bridgeMesh);
    this.bridges.set(bridgeId, bridgeMesh);
    return bridgeMesh;
  }

  /**
   * Generate a bridge between a conduit and a pipeline node organ.
   * The conduit blends into the organ at the organ's position.
   */
  generateConduitNodeBridge(
    bridgeId: string,
    conduitStart: THREE.Vector3,
    conduitEnd: THREE.Vector3,
    conduitRadius: number,
    nodeId: string,
    organPos: THREE.Vector3,
    organRadius: number,
    material: THREE.Material,
  ): THREE.Mesh | null {
    this.removeBridge(bridgeId);

    const decision = evaluateBlend(
      { kind: 'conduit', conduitId: bridgeId },
      { kind: 'pipelineNode', nodeId },
    );
    if (!decision.shouldBlend) return null;

    const conduitSDF = buildConduitSDF(conduitStart, conduitEnd, conduitRadius);
    const organSDF = buildPipelineNodeSDF(nodeId, organPos, organRadius);

    const bridgeGeo = generateBlendBridge(conduitSDF, organSDF, organPos, {
      blendRadius: decision.blendRadius,
      resolution: 24,
      regionPadding: Math.max(decision.blendRadius * 3, organRadius * 1.5),
    });
    if (!bridgeGeo) return null;

    const bridgeMesh = new THREE.Mesh(bridgeGeo, material);
    bridgeMesh.userData = {
      name: `Conduit-${nodeId} Blend Bridge`,
      category: 'Anatomical Blend Fillet',
      desc: `Seamless SDF smooth-union fillet (${decision.reason}).`,
      isBlendBridge: true,
      bridgeId,
    };
    this.shipGroup.add(bridgeMesh);
    this.bridges.set(bridgeId, bridgeMesh);
    return bridgeMesh;
  }

  /**
   * Generate a bridge between a conduit (auto-wire vein) and a candidate organ.
   */
  generateConduitOrganBridge(
    bridgeId: string,
    conduitStart: THREE.Vector3,
    conduitEnd: THREE.Vector3,
    conduitRadius: number,
    organType: string,
    organPos: THREE.Vector3,
    organNormal: THREE.Vector3,
    organSize: number,
    material: THREE.Material,
  ): THREE.Mesh | null {
    this.removeBridge(bridgeId);

    const decision = evaluateBlend(
      { kind: 'conduit', conduitId: bridgeId },
      { kind: 'organ', organType },
    );
    if (!decision.shouldBlend) return null;

    const conduitSDF = buildConduitSDF(conduitStart, conduitEnd, conduitRadius);
    const organSDF = buildCandidateOrganSDF(organType, organPos, organNormal, organSize);
    if (!organSDF) return null;

    const bridgeGeo = generateBlendBridge(conduitSDF, organSDF, organPos, {
      blendRadius: decision.blendRadius,
      resolution: 20,
      regionPadding: Math.max(decision.blendRadius * 3, organSize * 1.5),
    });
    if (!bridgeGeo) return null;

    const bridgeMesh = new THREE.Mesh(bridgeGeo, material);
    bridgeMesh.userData = {
      name: `Vein-${organType} Blend Bridge`,
      category: 'Anatomical Blend Fillet',
      desc: `Seamless SDF smooth-union fillet (${decision.reason}).`,
      isBlendBridge: true,
      bridgeId,
    };
    this.shipGroup.add(bridgeMesh);
    this.bridges.set(bridgeId, bridgeMesh);
    return bridgeMesh;
  }

  /** Remove a single bridge by ID. */
  removeBridge(bridgeId: string): void {
    const existing = this.bridges.get(bridgeId);
    if (existing) {
      this.shipGroup.remove(existing);
      existing.geometry.dispose();
      this.bridges.delete(bridgeId);
    }
  }

  /** Remove all bridges whose ID starts with the given prefix (for drag regeneration). */
  removeBridgesWithPrefix(prefix: string): void {
    const toRemove: string[] = [];
    for (const [id, mesh] of this.bridges) {
      if (id.startsWith(prefix)) {
        this.shipGroup.remove(mesh);
        mesh.geometry.dispose();
        toRemove.push(id);
      }
    }
    toRemove.forEach(id => this.bridges.delete(id));
  }

  /** Regenerate the hull SDF after hull adaptation (call on drag).
   * Reuses the cross-section height factor from setHullSDF. */
  regenerateHullSDF(spineNodes: SpineNode[]): void {
    this.spineNodes = spineNodes;
    this.hullSDF = buildHullSDF(spineNodes, this.heightFactor);
  }

  /**
   * Regenerate all hull-blend bridges for a specific candidate organ.
   * Called during drag to keep bridges attached to the moved organ.
   */
  regenerateOrganHullBridge(
    organId: string,
    organType: string,
    basePos: THREE.Vector3,
    normal: THREE.Vector3,
    size: number,
    stalkLength: number,
    material: THREE.Material,
  ): void {
    this.removeBridgesWithPrefix(`organ_${organId}`);
    this.generateOrganHullBridge(`organ_${organId}`, organType, basePos, normal, size, stalkLength, material);
  }

  /** Clear all bridges (call before full scene rebuild). */
  clear(): void {
    for (const [, mesh] of this.bridges) {
      this.shipGroup.remove(mesh);
      mesh.geometry.dispose();
    }
    this.bridges.clear();
  }

  /** Get the number of active bridges. */
  get count(): number {
    return this.bridges.size;
  }
}

