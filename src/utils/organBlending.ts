/**
 * Organ Blending — Anatomical-Aware Seamless Connection System
 *
 * Implements the SDF smooth-union seamless-connection approach (see Gemini research
 * and docs/research/PROCEDURAL_MESH_GENERATION_RESEARCH.md §5.1) with per-connection
 * anatomical rules. Each blend decision (organ↔organ, organ↔hull, conduit↔organ) is
 * evaluated individually against a data-driven registry that encodes which
 * connections should be seamlessly blended and which should remain discrete.
 *
 * Design rationale:
 *   - Static organs (heart, brain, glands, habitat, eyes) → can be SDF-blended
 *     because their position is fixed at build time.
 *   - Animated organs (tentacles with IK, pulsing neural nodes) → keep the existing
 *     socket collar approach; the connection point is fixed but the organ moves, so
 *     a static SDF bridge would detach during animation.
 *   - The hull is represented as an analytic swept-sphere SDF approximation built
 *     from the spine nodes, so it can participate in blends without expensive
 *     mesh-to-SDF conversion of the parametric hull mesh.
 *   - Movable candidate organs (eye, neural, spore) → bridges regenerate on drag
 *     via BlendBridgeManager.
 *
 * The bridge mesh is generated by sampling opSmoothUnion(sdfA, sdfB, k) in a local
 * bounding region around the connection point and extracting the isosurface via
 * marching cubes. This produces a seamless fillet that visually grows the organ out
 * of the hull (or two organs into each other) while preserving per-organ animation
 * and selection — the bridge is a separate mesh that overlaps slightly with both
 * parents, hidden inside them except in the blend zone.
 *
 * References:
 *   - Inigo Quilez: "smooth minimum" — iquilezles.org
 *   - Gemini: "Volumetric & Implicit Remeshing" (SDF + smin + Marching Cubes)
 */

