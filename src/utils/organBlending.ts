const isVascularNode = (e: BlendEntity): e is { kind: 'pipelineNode'; nodeId: string } =>
  isNode(e, ...VASCULAR_NODES);

/** True if the entity is an exoskeleton surface node. */
const isExoskeletonNode = (e: BlendEntity): e is { kind: 'pipelineNode'; nodeId: string } =>
  isNode(e, ...EXOSKELETON_NODES);

/** True if the entity is a muscular/internal structural node. */
const isMuscularNode = (e: BlendEntity): e is { kind: 'pipelineNode'; nodeId: string } =>
  isNode(e, ...MUSCULAR_NODES);

// ── Complete Anatomical Blend Rules Matrix ──
//
// Every possible interaction pair is evaluated against these rules in order.
// The first matching rule wins. This makes every blend decision explicit and
// individually auditable.
//
// Categories covered:
//   1. Conduit → organ (all 19 pipeline conduits blend into their endpoints)
//   2. Vascular auto-wire → candidate organ (vein roots into organ)
//   3. Exoskeleton effectors → hull (surface growth)
//   4. Candidate organs → hull (movable surface organs)
//   5. Adjacent organ pairs that share tissue (heart↔atrium, brain↔neurolink, etc.)
//   6. Habitat → cyber_airlock (hallway connection — user confirmed)
//   7. Internal organs → hull (NO — they live inside)
//   8. Animated organs → hull (NO — keep socket collar)
//   9. Habitat → anything except airlock (NO — user confirmed)
//  10. Conduit → hull (NO — conduits are internal)
//  11. Conduit → conduit (NO — conduits branch at manifolds, not blend)
//  12. Cross-pipeline organ pairs (NO — organs from different pipelines stay discrete)
//  13. Default: conservative no-blend

const RULES: BlendRule[] = [
  // ── 1. Conduit → organ (seamless root blending) ──
  // Every conduit in CONDUIT_DEFS blends seamlessly into its source and target
  // organs. This is the "veins to heart" pattern — the conduit grows into the
  // organ as a seamless tissue transition.
  (a, b) => {
    if (isConduit(a) && b.kind === 'pipelineNode') {
      return blend(0.2, 'vein', `conduit roots into ${b.nodeId}`);
    }
    if (isConduit(b) && a.kind === 'pipelineNode') {
      return blend(0.2, 'vein', `${a.nodeId} roots into conduit`);
    }
    return null;
  },

  // ── 2. Conduit → candidate organ (vascular auto-wire) ──
  // Auto-wired veins from the central aorta blend into each candidate organ
  // they supply. The vein roots seamlessly into the organ's socket.
  (a, b) => {
    if (isConduit(a) && isOrganType(b, 'eye', 'neural', 'spore', 'spiracle', 'rib', 'habitat', 'tentacle')) {
      return blend(0.12, 'vein', `auto-wire vein roots into ${b.organType}`);
    }
    if (isConduit(b) && isOrganType(a, 'eye', 'neural', 'spore', 'spiracle', 'rib', 'habitat', 'tentacle')) {
      return blend(0.12, 'vein', `${a.organType} roots into auto-wire vein`);
    }
    return null;
  },

  // ── 3. Exoskeleton effectors → hull (surface growth, fixed) ──
  // Pipeline nodes on the exoskeleton layer grow seamlessly from the hull.
  // These are fixed-position effectors (thrusters, gills, eyes, airlocks, shields).
  (a, b) => {
    if (isExoskeletonNode(a) && b.kind === 'hull') {
      return blend(0.15, 'carapace', `${a.nodeId} grows from hull surface`);
    }
    if (isExoskeletonNode(b) && a.kind === 'hull') {
      return blend(0.15, 'carapace', `hull grows around ${b.nodeId}`);
    }
    return null;
  },

  // ── 4. Candidate organs → hull (movable surface organs) ──
  // Surface-mounted candidate organs that should grow seamlessly from the hull.
  // These are static or slow-animated organs where a fixed bridge is appropriate.
  (a, b) => {
    // Eyes → hull: YES (user confirmed)
    if (isOrganType(a, 'eye') && b.kind === 'hull') {
      return blend(0.15, 'carapace', 'eye stalk roots seamlessly into hull');
    }
    if (isOrganType(b, 'eye') && a.kind === 'hull') {
      return blend(0.15, 'carapace', 'hull grows around eye stalk base');
    }
    // Neural sensory nodes → hull: YES (sensory organs grow from surface)
    if (isOrganType(a, 'neural') && b.kind === 'hull') {
      return blend(0.12, 'carapace', 'neural node roots into hull surface');
    }
    if (isOrganType(b, 'neural') && a.kind === 'hull') {
      return blend(0.12, 'carapace', 'hull grows around neural node');
    }
    // Spore sacs → hull: YES (surface growth)
    if (isOrganType(a, 'spore') && b.kind === 'hull') {
      return blend(0.14, 'flesh', 'spore sac grows from hull surface');
    }
    if (isOrganType(b, 'spore') && a.kind === 'hull') {
      return blend(0.14, 'flesh', 'hull surface grows around spore sac');
    }

    // Pectoral Fin → hull: YES
    if (isOrganType(a, 'pectoralFin') && b.kind === 'hull') {
      return blend(0.25, 'carapace', 'pectoral fin blends seamlessly into hull');
    }
    if (isOrganType(b, 'pectoralFin') && a.kind === 'hull') {
      return blend(0.25, 'carapace', 'hull surface grows around pectoral fin');
    }

    // Caudal Fluke → hull: YES
    if (isOrganType(a, 'caudalFluke') && b.kind === 'hull') {
      return blend(0.25, 'carapace', 'caudal fluke blends seamlessly into hull');
    }
    if (isOrganType(b, 'caudalFluke') && a.kind === 'hull') {
      return blend(0.25, 'carapace', 'hull surface grows around caudal fluke');
    }

    // Dorsal Sail → hull: YES
    if (isOrganType(a, 'dorsalSail') && b.kind === 'hull') {
      return blend(0.25, 'carapace', 'dorsal sail blends seamlessly into hull');
    }
    if (isOrganType(b, 'dorsalSail') && a.kind === 'hull') {
      return blend(0.25, 'carapace', 'hull surface grows around dorsal sail');
    }
    return null;
  },

  // ── 5. Adjacent organ pairs sharing tissue ──
  // These organ pairs are directly connected and share tissue — they should
  // blend seamlessly. Not all adjacent pipeline nodes blend; only those where
  // the anatomy calls for tissue continuity (not just a conduit connection).
  (a, b) => {
    // Heart ↔ hemolymph atrium: YES (atrium is cardiac extension)
    if (isNode(a, 'heart_core') && isNode(b, 'hemolymph_atrium')) {
      return blend(0.25, 'vein', 'atrium is cardiac extension of heart');
    }
    if (isNode(b, 'heart_core') && isNode(a, 'hemolymph_atrium')) {
      return blend(0.25, 'vein', 'atrium is cardiac extension of heart');
    }
    // Brain ↔ neuro-link: YES (neuro-link plugs directly into brain)
    if (isNode(a, 'brain_core') && isNode(b, 'neuro_link')) {
      return blend(0.15, 'flesh', 'neuro-link plugs into brain core');
    }
    if (isNode(b, 'brain_core') && isNode(a, 'neuro_link')) {
      return blend(0.15, 'flesh', 'neuro-link plugs into brain core');
    }
    // Plasma gland ↔ plasma bladder: YES (gland feeds directly into bladder)
    if (isNode(a, 'plasma_gland') && isNode(b, 'plasma_bladder')) {
      return blend(0.18, 'flesh', 'plasma gland grows into bladder');
    }
    if (isNode(b, 'plasma_gland') && isNode(a, 'plasma_bladder')) {
      return blend(0.18, 'flesh', 'plasma gland grows into bladder');
    }
    // Carapace plate ↔ bio-nanite bed: YES (nanite bed is sub-dermal under carapace)
    if (isNode(a, 'carapace_plate') && isNode(b, 'bio_nanite_bed')) {
      return blend(0.15, 'flesh', 'nanite bed is sub-dermal under carapace');
    }
    if (isNode(b, 'carapace_plate') && isNode(a, 'bio_nanite_bed')) {
      return blend(0.15, 'flesh', 'nanite bed is sub-dermal under carapace');
    }
    // Bio-nanite bed ↔ shield emitter: YES (nanite feeds shield emitter)
    if (isNode(a, 'bio_nanite_bed') && isNode(b, 'shield_emitter')) {
      return blend(0.12, 'flesh', 'nanite bed feeds shield emitter');
    }
    if (isNode(b, 'bio_nanite_bed') && isNode(a, 'shield_emitter')) {
      return blend(0.12, 'flesh', 'nanite bed feeds shield emitter');
    }
    // Chitin vertebra ↔ carapace plate: YES (vertebra supports carapace)
    if (isNode(a, 'chitin_vertebra') && isNode(b, 'carapace_plate')) {
      return blend(0.15, 'carapace', 'vertebra supports carapace plate');
    }
    if (isNode(b, 'chitin_vertebra') && isNode(a, 'carapace_plate')) {
      return blend(0.15, 'carapace', 'vertebra supports carapace plate');
    }
    return null;
  },

  // ── 6. Habitat → cyber_airlock (hallway connection) ──
  // The habitat chamber blends seamlessly into its connecting airlock/hallway.
  // User confirmed: "habitat to anything other than hallway no" → airlock = hallway = YES.
  (a, b) => {
    if (isOrganType(a, 'habitat') && isNode(b, 'cyber_airlock')) {
      return blend(0.2, 'flesh', 'habitat blends into cyber airlock hallway');
    }
    if (isOrganType(b, 'habitat') && isNode(a, 'cyber_airlock')) {
      return blend(0.2, 'flesh', 'cyber airlock hallway blends into habitat');
    }
    // Pipeline node habitat_chamber → cyber_airlock: YES
    if (isNode(a, 'habitat_chamber') && isNode(b, 'cyber_airlock')) {
      return blend(0.2, 'flesh', 'habitat chamber blends into airlock');
    }
    if (isNode(b, 'habitat_chamber') && isNode(a, 'cyber_airlock')) {
      return blend(0.2, 'flesh', 'airlock blends into habitat chamber');
    }
    return null;
  },

  // ── 7. Internal organs → hull: NO ──
  // Heart, brain, glands, bladders, atria are internal and must not fuse with
  // the hull — they are discrete organs suspended within the body cavity.
  (a, b) => {
    if ((isInternalOrgan(a) || isVascularNode(a) || isMuscularNode(a)) && b.kind === 'hull') {
      return noBlend('internal organ must not fuse with hull', 'flesh');
    }
    if ((isInternalOrgan(b) || isVascularNode(b) || isMuscularNode(b)) && a.kind === 'hull') {
      return noBlend('internal organ must not fuse with hull', 'flesh');
    }
    return null;
  },

  // ── 8. Animated/discrete candidate organs → hull: NO ──
  // Tentacles use FABRIK IK — a static bridge would detach during animation.
  // Spiracles flex — a static bridge would detach during flex.
  // Ribs are discrete armor segments — they don't grow from the hull.
  (a, b) => {
    if (isOrganType(a, 'tentacle') && b.kind === 'hull') {
      return noBlend('tentacle uses animated IK — socket collar retained', 'flesh');
    }
    if (isOrganType(b, 'tentacle') && a.kind === 'hull') {
      return noBlend('tentacle uses animated IK — socket collar retained', 'flesh');
    }
    if (isOrganType(a, 'spiracle') && b.kind === 'hull') {
      return noBlend('spiracle flexes — socket collar retained', 'carapace');
    }
    if (isOrganType(b, 'spiracle') && a.kind === 'hull') {
      return noBlend('spiracle flexes — socket collar retained', 'carapace');
    }
    if (isOrganType(a, 'rib') && b.kind === 'hull') {
      return noBlend('rib is a discrete armor segment — no hull blend', 'carapace');
    }
    if (isOrganType(b, 'rib') && a.kind === 'hull') {
      return noBlend('rib is a discrete armor segment — no hull blend', 'carapace');
    }
    return null;
  },

  // ── 9. Habitat → anything except cyber_airlock: NO ──
  // User confirmed: "habitat to anything other than hallway no".
  // Habitat chambers are discrete pressurized volumes — they don't blend with
  // the hull, other organs, or conduits (except their airlock hallway).
  (a, b) => {
    if (isOrganType(a, 'habitat') && !isNode(b, 'cyber_airlock')) {
      return noBlend('habitat is discrete — only blends with cyber airlock', 'flesh');
    }
    if (isOrganType(b, 'habitat') && !isNode(a, 'cyber_airlock')) {
      return noBlend('habitat is discrete — only blends with cyber airlock', 'flesh');
    }
    if (isNode(a, 'habitat_chamber') && !isNode(b, 'cyber_airlock') && !isConduit(b)) {
      return noBlend('habitat chamber is discrete — only blends with airlock', 'flesh');
    }
    if (isNode(b, 'habitat_chamber') && !isNode(a, 'cyber_airlock') && !isConduit(a)) {
      return noBlend('habitat chamber is discrete — only blends with airlock', 'flesh');
    }
    return null;
  },

  // ── 10. Conduit → hull: NO ──
  // Conduits are internal transport — they don't break through the hull
  // (except at effectors, which are handled by the exoskeleton→hull rule).
  (a, b) => {
    if (isConduit(a) && b.kind === 'hull') {
      return noBlend('conduit is internal — does not break through hull', 'vein');
    }
    if (isConduit(b) && a.kind === 'hull') {
      return noBlend('conduit is internal — does not break through hull', 'vein');
    }
    return null;
  },

  // ── 11. Conduit → conduit: NO ──
  // Conduits branch at manifolds, not by blending. Each conduit is a discrete
  // tube that connects to organs, not to other conduits.
  (a, b) => {
    if (isConduit(a) && isConduit(b)) {
      return noBlend('conduits branch at manifolds — no conduit-conduit blend', 'vein');
    }
    return null;
  },

  // ── 12. Non-adjacent organ pairs: NO ──
  // Organs that are not in the tissue-sharing list (rule 5) stay discrete.
  // They are connected by conduits, not by direct tissue continuity.
  (a, b) => {
    if (a.kind === 'pipelineNode' && b.kind === 'pipelineNode') {
      return noBlend('non-adjacent organs stay discrete — connected by conduit', 'flesh');
    }
    return null;
  },

  // ── 13. Candidate organ → pipeline node: NO ──
  // Candidate organs (surface-mounted) don't blend with internal pipeline nodes
  // — they're in different anatomical layers. The vascular auto-wire handles
  // the connection via a conduit.
  (a, b) => {
    if (isOrganType(a) && b.kind === 'pipelineNode' && !isConduit(b)) {
      return noBlend('candidate organ and pipeline node are in different layers', 'flesh');
    }
    if (isOrganType(b) && a.kind === 'pipelineNode' && !isConduit(a)) {
      return noBlend('candidate organ and pipeline node are in different layers', 'flesh');
    }
    return null;
  },

  // ── 14. Candidate organ → candidate organ: NO ──
  // Candidate organs don't blend with each other — they're discrete surface
  // features separated by the force-field solver.
  (a, b) => {
    if (isOrganType(a) && isOrganType(b)) {
      return noBlend('candidate organs are discrete — separated by force field', 'flesh');
    }
    return null;
  },
];

/**
 * Evaluate whether two entities should be seamlessly blended.
 *
 * This is the single entry point for anatomical blend decisions. Every
 * connection is evaluated individually against the rules registry.
 *
 * @param a First entity (organ, pipeline node, conduit, or hull).
 * @param b Second entity (organ, pipeline node, conduit, or hull).
 * @returns Blend decision with shouldBlend, blendRadius, and materialRole.
 */
export function evaluateBlend(a: BlendEntity, b: BlendEntity): BlendDecision {
  for (const rule of RULES) {
    const result = rule(a, b);
    if (result !== null) return result;
  }
  return noBlend('no anatomical rule matches — conservative no-blend', 'flesh');
}

// ── Blend Bridge Generation ──

export interface BlendBridgeOptions {
  blendRadius: number;
  resolution?: number;
  regionPadding?: number;
}

/**
 * Generate a seamless blend bridge mesh between two SDFs.
 *
 * Samples `opSmoothUnion(sdfA, sdfB, k)` in a local bounding region around the
 * connection point and extracts the isosurface via marching cubes.
 */
export function generateBlendBridge(
  sdfA: SDF,
  sdfB: SDF,
  connectionPoint: THREE.Vector3,
  options: BlendBridgeOptions,
): THREE.BufferGeometry | null {
  const k = options.blendRadius;
  const resolution = options.resolution ?? 24;
  const padding = options.regionPadding ?? Math.max(k * 3, 0.5);

  const bounds = new THREE.Box3(
    connectionPoint.clone().subScalar(padding),
    connectionPoint.clone().addScalar(padding),
  );

  const blendedSDF = opSmoothUnion(sdfA, sdfB, k);
  const values = sampleSDFGrid(blendedSDF, bounds, resolution);

  // Guard against NaN values in the SDF grid (can happen if SDFs produce
  // NaN at degenerate positions, e.g. zero-length capsules).
  let hasNaN = false;
  for (let i = 0; i < values.length; i++) {
    if (isNaN(values[i]) || !isFinite(values[i])) {
      hasNaN = true;
      break;
    }
  }
  if (hasNaN) {
    releaseSDFGridBuffer(values);
    return null;
  }

  const geometry = marchingCubes(values, resolution, bounds, { computeNormals: true });
  releaseSDFGridBuffer(values);

  if (!geometry.getAttribute('position') || geometry.getAttribute('position').count === 0) {
    return null;
  }

  // Guard against NaN vertices in the generated geometry.
  const positions = geometry.getAttribute('position');
  for (let i = 0; i < positions.count; i++) {
    if (isNaN(positions.getX(i)) || isNaN(positions.getY(i)) || isNaN(positions.getZ(i))) {
      return null;
    }
  }

  return geometry;
}

