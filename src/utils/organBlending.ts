/**
 * Build a capsule SDF between two world-space points.
 */
function buildAlignedCapsuleSDF(
  start: THREE.Vector3,
  end: THREE.Vector3,
  radius: number,
): SDF {
  const direction = new THREE.Vector3().subVectors(end, start);
  const length = direction.length();
  if (length < 1e-6) {
    return opTranslate(sdSphere(radius), start);
  }
  const dir = direction.clone().normalize();
  const yAxis = new THREE.Vector3(0, 1, 0);
  const quat = new THREE.Quaternion().setFromUnitVectors(yAxis, dir);
  const rotMatrix = new THREE.Matrix3().setFromMatrix4(
    new THREE.Matrix4().makeRotationFromQuaternion(quat),
  );
  const mid = start.clone().lerp(end, 0.5);
  const capsule = sdCapsule(radius, length * 0.5);
  return opTranslate(opRotate(capsule, rotMatrix), mid);
}
